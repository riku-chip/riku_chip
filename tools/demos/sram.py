"""Demo `sram`: una SRAM de 16 palabras de 8 bits de SKY130 (OpenRAM) con 7
commits, una rama y un merge. Muestra jerarquía: un cambio en una sub-celda
aparece en cada una de sus instancias.

Fuente: `examples/GDS/sram_16x8_sky130.gds` (OpenRAM, BSD-3-Clause; celdas de
SkyWater, Apache-2.0).

    python3 tools/demos/sram.py <salida.bundle>
"""
import os
import sys

import klayout.db as db

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import Repo  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "examples", "GDS", "sram_16x8_sky130.gds")
GDS = "sram_16x8_sky130.gds"
BITCELL_MET2 = "sky130_fd_bd_sram__sram_sp_cell_met2"
DFF = "sky130_fd_bd_sram__openram_dff"
PMOS = "sram_16x8_sky130_pmos_m1_w1_120_sli_dli_da_p"
BANK = "sram_16x8_sky130_bank"

README = """# 16×8 SRAM (SKY130, OpenRAM) · Riku demo

A 16-word × 8-bit SRAM macro generated by OpenRAM for SKY130: 157 cells, the
bitcell placed 153 times. Seven commits with a branch (`fill`) and a merge,
to see how Riku shows changes deep in a hierarchy.

Things to try:

```bash
riku log --graph                          # the history
riku show HEAD~3                          # a bitcell change, seen in its 153 instances
riku show HEAD~2                          # a renamed cell (same geometry)
riku show fill                            # metal4 fill: hundreds of polygons, XOR by quadrants
riku diff v0.1 v1.0 -f visual             # the whole macro in the viewer
riku open                                 # H opens the history; the Cells list filters "only changed"
```

Source: `sram_16x8_sky130` generated with [OpenRAM](https://github.com/VLSIDA/OpenRAM)
(BSD-3-Clause) using the SkyWater SRAM cells (Apache-2.0); see `LICENSE`. The
changes are Riku's, to show its diffs.
"""

